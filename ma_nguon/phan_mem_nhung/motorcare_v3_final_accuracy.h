inline bool predict(const float* x, float* p) {
  for (int c = 0; c < CLASSES; ++c) p[c] = 0.0f;
  for (int i = 0; i < FEATURES; ++i) if (!std::isfinite(x[i])) return false;
  float pm[3] = {0.0f, 0.0f, 0.0f};
  for (int t = 0; t < MECH_TREES; ++t) {
    uint16_t i = mech_roots[t];
    while (mech_nodes[i].feature >= 0) {
      const auto &n = mech_nodes[i];
      i = x[n.feature] <= n.threshold ? n.left : n.right;
    }
    for (int c = 0; c < 3; ++c) pm[c] += mech_leaves[mech_nodes[i].leaf][c];
  }
  for (int c = 0; c < 3; ++c) pm[c] /= float(MECH_TREES);
  const float* xe = x + MECH_FEATURES;
  float ps = 0.0f;
  for (int t = 0; t < ELEC_TREES; ++t) {
    uint16_t i = elec_roots[t];
    while (elec_nodes[i].feature >= 0) {
      const auto &n = elec_nodes[i];
      i = xe[n.feature] <= n.threshold ? n.left : n.right;
    }
    ps += elec_leaves[elec_nodes[i].leaf][1];
  }
  ps /= float(ELEC_TREES);
  // 5-Stage SO(3)-Invariant Physics Guardrails
  if (x[IDX_GDYN_MED] < 0.038f && x[IDX_STEP_MED] < 0.075f) { pm[1] += pm[2]; pm[2] = 0.0f; }
  if (x[IDX_GDYN_MED] < 0.165f && x[IDX_ACF_LAG2] < 0.28f && x[IDX_CUR_CV] < 0.085f) { pm[1] += pm[2]; pm[2] = 0.0f; }
  if (x[IDX_STEP_MED] > 0.080f && (x[IDX_CUR_CV] > 0.095f || x[IDX_ACF_LAG2] > 0.40f) && x[IDX_COV_STD3] > 0.0080f && x[IDX_WHIRL_NORM] > 0.19f) { pm[2] += pm[1]; pm[1] = 0.0f; }
  if (x[IDX_CUR_CV] > 0.025f && x[IDX_STEP_RATIO] > 1.60f) { pm[1] += pm[0]; pm[0] = 0.0f; }
  if (ps > 0.5f && x[IDX_V_MED] < 8.5f && x[IDX_CUR_CV] > 0.015f) { pm[1] += pm[0]; pm[0] = 0.0f; }
  const float s0 = 1.0f - ps;
  p[0] = pm[0] * s0; p[1] = pm[0] * ps;
  p[2] = pm[1] * s0; p[3] = pm[1] * ps;
  p[4] = pm[2] * s0; p[5] = pm[2] * ps;
  return true;
}
